// Nuante -700: text alb mic pe ele trece pragul WCAG AA (4.5:1).
const AVATAR_STYLES = [
  "bg-sky-700",
  "bg-amber-700",
  "bg-emerald-700",
  "bg-rose-700",
  "bg-violet-700",
  "bg-indigo-700",
  "bg-teal-700",
];

function initials(name: string): string {
  return name
    .split(" ")
    .filter(Boolean)
    .slice(0, 2)
    .map((part) => part[0])
    .join("")
    .toUpperCase();
}

function StarRow() {
  return (
    <div className="flex gap-0.5 text-amber-400" aria-label="Evaluare: 5 din 5 stele">
      {Array.from({ length: 5 }).map((_, i) => (
        <svg key={i} viewBox="0 0 20 20" fill="currentColor" className="h-4 w-4">
          <path d="M10 1.5l2.59 5.25 5.79.84-4.19 4.09.99 5.77L10 14.9l-5.18 2.55.99-5.77L1.62 7.6l5.79-.84L10 1.5z" />
        </svg>
      ))}
    </div>
  );
}

